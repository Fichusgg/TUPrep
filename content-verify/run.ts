/**
 * npm run verify:content
 * Re-computes every answer key that declares a verifier and writes content-verify/REPORT.md
 * listing each question with its verification status. Exits 1 if any verifier disagrees.
 */
import fs from "node:fs";
import path from "node:path";
import { Mock, QuestionFile, type Question } from "../src/content/schema";
import { listJson, readJson, ROOT } from "./lib/load";
import { verifyQuestion, type VerifyResult } from "./lib/verify";

const items: { q: Question; source: string }[] = [];
for (const rel of listJson("questions")) for (const q of QuestionFile.parse(readJson(rel))) items.push({ q, source: rel });
for (const rel of listJson("tests").filter((f) => /mock-\d+\.json$/.test(f))) {
  for (const s of Mock.parse(readJson(rel)).sections) for (const q of s.questions) items.push({ q, source: rel });
}

const only = process.argv.slice(2).filter((a) => !a.startsWith("-"));
const results: (VerifyResult & { source: string; unit: string; difficulty: number })[] = [];
for (const { q, source } of items) {
  if (only.length && !only.some((o) => q.id.startsWith(o) || source.includes(o))) continue;
  results.push({ ...verifyQuestion(q), source, unit: q.unit, difficulty: q.difficulty });
}

const by = (s: string) => results.filter((r) => r.status === s);
const failed = [...by("failed"), ...by("missing")];
for (const r of failed) console.error(`FAIL ${r.id} (${r.source}, ${r.method}): ${r.detail}`);

if (!only.length) {
  const units = [...new Set(results.map((r) => r.unit))].sort();
  const lines = [
    "# Content verification report",
    "",
    `Generated by \`npm run verify:content\` on ${new Date().toISOString().slice(0, 10)}.`,
    "",
    `- Questions checked: **${results.length}**`,
    `- Machine-verified: **${by("verified").length}**`,
    `- Manual (could not be machine-verified, checked by hand): **${by("manual").length}**`,
    `- Failed: **${failed.length}**`,
    "",
    "## Summary per unit",
    "",
    "| Unit | Questions | Machine-verified | Manual | Failed |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...units.map((u) => {
      const rs = results.filter((r) => r.unit === u);
      const c = (s: string) => rs.filter((r) => r.status === s).length;
      return `| ${u} | ${rs.length} | ${c("verified")} | ${c("manual")} | ${c("failed") + c("missing")} |`;
    }),
    "",
    "## Manual questions",
    "",
    ...(by("manual").length ? by("manual").map((r) => `- **${r.id}** (${r.source}): ${r.detail}`) : ["None."]),
    "",
    "## Every question",
    "",
    "| Id | Source | Unit | Diff | Method | Status | Detail |",
    "| --- | --- | --- | ---: | --- | --- | --- |",
    ...results.map((r) => `| ${r.id} | ${r.source} | ${r.unit} | ${r.difficulty} | ${r.method} | ${r.status} | ${r.detail.replace(/\|/g, "\\|")} |`),
    "",
  ];
  fs.writeFileSync(path.join(ROOT, "content-verify", "REPORT.md"), lines.join("\n"));
}

console.log(`\nverify:content — ${results.length} checked, ${by("verified").length} machine-verified, ${by("manual").length} manual, ${failed.length} failed.`);
if (!only.length) console.log("Report written to content-verify/REPORT.md");
if (failed.length) process.exit(1);
